package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"strings"
)

// manifestSchema is the only manifest schema version this installer accepts.
const manifestSchema = 1

// Supported variant identifiers. The short names are accepted on the command
// line, but the manifest and the resolved variant always use the full name.
const (
	variantModernAMD64 = "modern-amd64"
	variantLegacyAMD64 = "legacy-amd64"
)

// OSVersion is the Windows NT version reported by RtlGetVersion.
type OSVersion struct {
	Major uint32
	Minor uint32
	Build uint32
}

// Manifest describes the Windows Edge artifacts published by the Manager.
type Manifest struct {
	Schema   int       `json:"schema"`
	Version  string    `json:"version"`
	Variants []Variant `json:"variants"`
}

// Variant is a complete artifact set for one Windows compatibility level.
type Variant struct {
	ID    string `json:"id"`
	MinOS MinOS  `json:"min_os"`
	Files []File `json:"files"`
}

// MinOS is the minimum NT version a variant supports.
type MinOS struct {
	Major uint32 `json:"major"`
	Minor uint32 `json:"minor"`
	Build uint32 `json:"build"`
}

// File is one artifact within a variant.
type File struct {
	Path   string `json:"path"`
	SHA256 string `json:"sha256"`
	Dest   string `json:"dest"`
}

// ParseManifest decodes and validates a manifest. Unknown fields, duplicate
// JSON payloads, unsafe paths, unknown destinations, and malformed digests are
// rejected so a forged manifest cannot escape the install root.
func ParseManifest(data []byte) (*Manifest, error) {
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.DisallowUnknownFields()

	var m Manifest
	if err := dec.Decode(&m); err != nil {
		return nil, fmt.Errorf("parse manifest: %w", err)
	}
	var trailing json.RawMessage
	if err := dec.Decode(&trailing); err != io.EOF {
		return nil, errors.New("parse manifest: unexpected trailing data")
	}

	if err := m.validate(); err != nil {
		return nil, err
	}
	return &m, nil
}

func (m *Manifest) validate() error {
	if m.Schema != manifestSchema {
		return fmt.Errorf("parse manifest: unsupported schema %d, want %d", m.Schema, manifestSchema)
	}
	if len(m.Variants) == 0 {
		return errors.New("parse manifest: no variants")
	}
	for i := range m.Variants {
		v := &m.Variants[i]
		if v.ID == "" {
			return fmt.Errorf("parse manifest: variant %d has an empty id", i)
		}
		for j := range v.Files {
			f := &v.Files[j]
			if err := validateRelativePath(f.Path); err != nil {
				return fmt.Errorf("parse manifest: variant %q file %d: %w", v.ID, j, err)
			}
			if err := validateDest(f.Dest); err != nil {
				return fmt.Errorf("parse manifest: variant %q file %q: %w", v.ID, f.Path, err)
			}
			if err := validateSHA256(f.SHA256); err != nil {
				return fmt.Errorf("parse manifest: variant %q file %q: %w", v.ID, f.Path, err)
			}
		}
	}
	return nil
}

// validateRelativePath rejects absolute paths and parent-directory traversal on
// both Windows and Unix path syntax. The manifest is validated on the Manager
// and again on the Windows host, so the checks must not depend on the host OS.
func validateRelativePath(path string) error {
	if path == "" {
		return errors.New("path is empty")
	}
	if strings.HasPrefix(path, "/") || strings.HasPrefix(path, `\`) {
		return fmt.Errorf("path %q must be relative", path)
	}
	if len(path) >= 2 && path[1] == ':' && isASCIILetter(path[0]) {
		return fmt.Errorf("path %q must be relative", path)
	}

	normalized := strings.ReplaceAll(path, `\`, "/")
	if normalized == "." || strings.HasSuffix(normalized, "/") {
		return fmt.Errorf("path %q must name a file", path)
	}
	for _, part := range strings.Split(normalized, "/") {
		// Win32 strips trailing dots and spaces from path components, so
		// ".. ", "..." and similar spellings still resolve to a parent
		// directory. Reject empty components as well: only canonical relative
		// paths generated by the release script are accepted.
		if part == "" || strings.TrimRight(part, " .") == "" {
			return fmt.Errorf("path %q contains an unsafe component %q", path, part)
		}
	}
	return nil
}

func validateDest(dest string) error {
	switch dest {
	case "bin", "plugins", "etc":
		return nil
	default:
		return fmt.Errorf("dest %q must be one of bin, plugins, etc", dest)
	}
}

func validateSHA256(digest string) error {
	if len(digest) != 64 {
		return fmt.Errorf("sha256 must be 64 hex characters, got %d", len(digest))
	}
	for i := 0; i < len(digest); i++ {
		if !isHexDigit(digest[i]) {
			return fmt.Errorf("sha256 must be hexadecimal, found %q", digest[i])
		}
	}
	return nil
}

func isASCIILetter(b byte) bool {
	return (b >= 'a' && b <= 'z') || (b >= 'A' && b <= 'Z')
}

func isHexDigit(b byte) bool {
	return (b >= '0' && b <= '9') || (b >= 'a' && b <= 'f') || (b >= 'A' && b <= 'F')
}

// SelectVariant resolves an explicit variant or picks one from the Windows
// version. An explicit variant wins even when the OS is outside the supported
// matrix; auto selection never falls back to another variant.
func (m *Manifest) SelectVariant(version OSVersion, requested string) (*Variant, error) {
	switch strings.TrimSpace(requested) {
	case "", "auto":
		id, err := autoVariantID(version)
		if err != nil {
			return nil, err
		}
		return m.variantByID(id)
	case "modern", variantModernAMD64:
		return m.variantByID(variantModernAMD64)
	case "legacy", variantLegacyAMD64:
		return m.variantByID(variantLegacyAMD64)
	default:
		return nil, fmt.Errorf(
			"unknown variant %q: supported values are auto, modern, legacy, %s, %s",
			requested, variantModernAMD64, variantLegacyAMD64,
		)
	}
}

func autoVariantID(version OSVersion) (string, error) {
	switch {
	case version.Major >= 10 && version.Build >= 14393:
		return variantModernAMD64, nil
	case version.Major == 6 && version.Minor == 1 && version.Build >= 7601:
		return variantLegacyAMD64, nil
	default:
		return "", fmt.Errorf(
			"unsupported Windows version %d.%d build %d: supported variants are "+
				"%s (Windows 10 / Server 2016 or newer, build >= 14393) and "+
				"%s (Windows Server 2008 R2 SP1, 6.1 build >= 7601)",
			version.Major, version.Minor, version.Build,
			variantModernAMD64, variantLegacyAMD64,
		)
	}
}

func (m *Manifest) variantByID(id string) (*Variant, error) {
	for i := range m.Variants {
		if m.Variants[i].ID == id {
			return &m.Variants[i], nil
		}
	}
	return nil, fmt.Errorf("manifest does not contain variant %q", id)
}
